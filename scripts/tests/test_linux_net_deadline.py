#!/usr/bin/env python3
"""Deterministic regression for the POSIX network sleep deadline arithmetic.

``NET_Sleep`` (``src/linux/net.cpp``) is called by the server frame loop as
``NET_Sleep(1)``. It records a deadline with ``NET_DeadlineFromNow``, then asks
``NET_RemainingMs`` how long is left and hands that value to ``select()``. If
``NET_RemainingMs`` rounds a sub-millisecond remainder down to zero, the
``select()`` timeout is ``{0, 0}``: not a wait at all. ``select()`` returns
immediately, ``NET_Sleep`` returns immediately, the frame loop calls it again,
and an idle server spins at ~100% of a core with no players connected.

The gap that makes this real rather than theoretical: the deadline is recorded
at one instant and read at a slightly later one, so the remaining time is
almost never a whole number of milliseconds. Any remainder in ``1..999999``
nanoseconds is a live case, and it happens on every single call.

Nothing here is timing-sensitive. Both functions are extracted verbatim from
production and driven by a fake ``clock_gettime``, so the nanoseconds passed in
are exactly the nanoseconds the arithmetic sees. The live socket behaviour is
covered separately by ``tests/linux_net/test_net.cpp``; this file pins the
arithmetic and the case table.

Usage:
    python3 scripts/tests/test_linux_net_deadline.py [--cxx clang++] [--timeout 120]
"""

import argparse
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[2]
NET_SOURCE = ROOT / "src" / "linux" / "net.cpp"

EXTRACTED = ("NET_RemainingMs", "NET_DeadlineFromNow")

INT32_MAX = 2147483647

# (name, deadline sec/nsec, now sec/nsec, expected milliseconds)
#
# The four `sub-millisecond` rows are the hot-poll regression: the unfixed
# arithmetic reports 0 for all of them even though time remains, which is what
# turns NET_Sleep(1) into a spin. The rest pin behaviour that must not change.
CASES = (
    ("exact_equal",            100, 500000000, 100, 500000000, 0),
    ("expired_by_one_ns",      100, 500000000, 100, 500000001, 0),
    ("expired_by_one_second",  100, 0,         101, 0,         0),
    ("one_ns_remaining",       100, 500000001, 100, 500000000, 1),
    ("just_under_one_ms",      100, 500999999, 100, 500000000, 1),
    ("exactly_one_ms",         100, 501000000, 100, 500000000, 1),
    ("one_ms_plus_one_ns",     100, 501000001, 100, 500000000, 2),
    ("one_ms_plus_500us",      100, 501500000, 100, 500000000, 2),
    ("sec_crossing_neg_nsec",  101, 250000000, 100, 750000000, 500),
    ("sec_crossing_partial_ns", 101, 250000000, 100, 999999999, 251),
    ("sec_crossing_1ns_left",  101, 0,         100, 999999999, 1),
    ("huge_clamps",            10000000, 0,    0,   0,         INT32_MAX),
    ("huge_clamp_boundary",    2147483, 647483648, 0, 0,       INT32_MAX),
)

# NET_DeadlineFromNow(clock, msec) -> expected deadline. Covers the second
# normalisation the remaining-time arithmetic relies on, plus the 0 ms case
# that keeps NET_Sleep(0) immediate.
DEADLINE_CASES = (
    ("deadline_no_normalisation",  0, 300000000, 1,    0, 301000000),
    ("deadline_normalises_carry",  0, 999999999, 1,    1, 999999),
    ("deadline_more_than_a_second", 0, 5,        1500, 1, 500000005),
    ("deadline_zero_ms",           0, 123456789, 0,    0, 123456789),
    ("deadline_whole_seconds",     0, 42,        2000, 2, 42),
)

HEADER = """\
// Generated by scripts/tests/test_linux_net_deadline.py -- not a build target.
// NET_RemainingMs and NET_DeadlineFromNow are extracted verbatim from
// src/linux/net.cpp; clock_gettime is redirected to a fake so the nanoseconds
// the arithmetic sees are exactly the ones the case table names.

#include <errno.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include <time.h>

static struct timespec g_now;
static int g_clockFailures;
static int g_clockCalls;

static int FakeClockGetTime(clockid_t id, struct timespec *tp)
{
    (void)id;
    ++g_clockCalls;
    if (g_clockFailures > 0)
    {
        --g_clockFailures;
        errno = EINVAL;
        return -1;
    }
    *tp = g_now;
    return 0;
}

#define clock_gettime FakeClockGetTime

"""

FOOTER_SENTINEL = "// ---- end of extracted production code ----\n"


def extract_function(source: str, name: str) -> str:
    """Return the full definition of ``name`` (signature, body, trailing brace).

    Descriptions are matched as whole words, declarations ending in ``;`` are
    skipped, and the body is found by brace matching so a nested block cannot
    end the extraction early.
    """
    start = None
    for match in __import__("re").finditer(rf"(?<![\w:.>]){name}\s*\(", source):
        opening_paren = source.index("(", match.end() - 1)
        depth = 0
        index = opening_paren
        while index < len(source):
            if source[index] == "(":
                depth += 1
            elif source[index] == ")":
                depth -= 1
                if depth == 0:
                    break
            index += 1
        brace = source.find("{", index)
        semicolon = source.find(";", index)
        if brace == -1:
            continue
        if semicolon != -1 and semicolon < brace:
            continue        # forward declaration, not the definition
        start = match.start()
        break

    if start is None:
        raise SystemExit(f"could not find the definition of {name} in {NET_SOURCE}")

    # `start` is at the function name; walk back to the start of the line so the
    # extracted text keeps its storage class and return type.
    for _ in range(4):
        line_start = source.rfind("\n", 0, start) + 1
        declaration = source[line_start:source.index("(", start)].split()
        if len(declaration) > 1:
            start = line_start
            break
        if line_start == 0:
            raise SystemExit(f"could not find a return type for {name} in {NET_SOURCE}")
        start = line_start - 1
    else:
        raise SystemExit(f"could not find a return type for {name} in {NET_SOURCE}")

    brace = source.index("{", start)
    depth = 0
    index = brace
    while index < len(source):
        if source[index] == "{":
            depth += 1
        elif source[index] == "}":
            depth -= 1
            if depth == 0:
                return source[start:index + 1] + "\n"
        index += 1

    raise SystemExit(f"unbalanced braces while extracting {name} from {NET_SOURCE}")


def build_harness(extracted: str) -> str:
    """Assemble the C++ test program around the extracted production code."""

    cases = "\n".join(
        '    { "%s", %d, %ld, %d, %ld, %d, 0 },' % (name, dsec, dnsec, nsec, nnsec, expect)
        for name, dsec, dnsec, nsec, nnsec, expect in CASES
    )
    deadline_cases = "\n".join(
        '    { "%s", %d, %ld, %d, %d, %ld, 0 },' % (name, csec, cnsec, msec, esec, enssec)
        for name, csec, cnsec, msec, esec, enssec in DEADLINE_CASES
    )

    template = (
        HEADER
        + "// ---- extracted from src/linux/net.cpp (verbatim) ----\n"
        + extracted
        + FOOTER_SENTINEL
        + """
static int g_failures;
static int g_checks;

static void Check(int condition, const char *what)
{
    ++g_checks;
    if (!condition)
    {
        ++g_failures;
        printf("  FAIL  %s\\n", what);
    }
    else
    {
        printf("  ok    %s\\n", what);
    }
}

static void SetNow(int sec, long nsec)
{
    g_now.tv_sec = sec;
    g_now.tv_nsec = nsec;
}

struct RemainingCase
{
    const char *name;
    int dsec;
    long dnsec;
    int nsec;
    long nnsec;
    int expect;
    int pad;
};

struct DeadlineCase
{
    const char *name;
    int csec;
    long cnsec;
    int msec;
    int esec;
    long enssec;
    int pad;
};

static const struct RemainingCase g_remaining[] = {
__REMAINING__
};

static const struct DeadlineCase g_deadline[] = {
__DEADLINE__
};

int main(void)
{
    unsigned i;
    char label[512];

    setvbuf(stdout, NULL, _IONBF, 0);
    printf("deadline arithmetic for NET_Sleep (src/linux/net.cpp)\\n");
    printf("sizeof(void*)=%%u\\n", (unsigned)sizeof(void *));

    printf("\\n== NET_RemainingMs case table ==\\n");
    for (i = 0; i < sizeof(g_remaining) / sizeof(g_remaining[0]); ++i)
    {
        const struct RemainingCase *c = &g_remaining[i];
        struct timespec deadline;
        int got;

        deadline.tv_sec = c->dsec;
        deadline.tv_nsec = c->dnsec;
        SetNow(c->nsec, c->nnsec);
        got = NET_RemainingMs(&deadline);
        snprintf(label, sizeof(label), "%%s -> %%d ms (expected %%d)", c->name, got, c->expect);
        Check(got == c->expect, label);
    }

    printf("\\n== NET_DeadlineFromNow case table ==\\n");
    for (i = 0; i < sizeof(g_deadline) / sizeof(g_deadline[0]); ++i)
    {
        const struct DeadlineCase *c = &g_deadline[i];
        struct timespec deadline;

        memset(&deadline, 0x7F, sizeof(deadline));
        SetNow(c->csec, c->cnsec);
        NET_DeadlineFromNow(c->msec, &deadline);
        snprintf(label, sizeof(label), "%%s -> {%%ld, %%ld} (expected {%%d, %%ld})",
                 c->name, (long)deadline.tv_sec, (long)deadline.tv_nsec, c->esec, c->enssec);
        Check(deadline.tv_sec == c->esec && deadline.tv_nsec == c->enssec, label);
    }

    printf("\\n== every sub-millisecond remainder stays visible ==\\n");
    {
        // The reported scenario: the deadline is recorded, then read 1 ns
        // later. Sweeping the whole last millisecond proves no offset can
        // report 0 while time remains, which is what made select() poll.
        struct timespec deadline;
        int zeroReported = 0;
        long wrong = 0;

        SetNow(500, 300000000);
        NET_DeadlineFromNow(1, &deadline);

        for (long offset = 0; offset < 1000000; offset += 1)
        {
            long expected = 1;
            int got;

            SetNow(500, 300000000 + offset);
            got = NET_RemainingMs(&deadline);
            if (got == 0)
                ++zeroReported;
            if (expected > 0 && got != 1)
                ++wrong;
        }

        snprintf(label, sizeof(label),
                 "NET_Sleep(1) never reports a zero timeout while time remains (zeros: %%d, wrong: %%ld)",
                 zeroReported, wrong);
        Check(zeroReported == 0 && wrong == 0, label);
    }

    printf("\\n== the deadline reads that follow NET_DeadlineFromNow ==\\n");
    {
        // Exactly what NET_Sleep(1) does: record the deadline at T, read it
        // 1 ns later. Before the fix this returned 0 and select() polled.
        struct timespec deadline;
        int got;

        SetNow(700, 300000000);
        NET_DeadlineFromNow(1, &deadline);
        SetNow(700, 300000001);
        got = NET_RemainingMs(&deadline);
        snprintf(label, sizeof(label), "read 1 ns after the deadline -> %%d ms (expected 1)", got);
        Check(got == 1, label);

        SetNow(700, 300999998);
        got = NET_RemainingMs(&deadline);
        snprintf(label, sizeof(label), "read 1 ms minus 2 ns after -> %%d ms (expected 1)", got);
        Check(got == 1, label);

        SetNow(700, 301000001);
        got = NET_RemainingMs(&deadline);
        snprintf(label, sizeof(label), "read 1 ns past the deadline -> %%d ms (expected 0)", got);
        Check(got == 0, label);
    }

    printf("\\n== clock_gettime failure ==\\n");
    {
        struct timespec deadline;
        int got;

        deadline.tv_sec = 900;
        deadline.tv_nsec = 0;
        SetNow(1, 0);
        g_clockFailures = 1;
        got = NET_RemainingMs(&deadline);
        snprintf(label, sizeof(label), "clock read failure reports 0 ms (got %%d)", got);
        Check(got == 0, label);

        memset(&deadline, 0x7F, sizeof(deadline));
        g_clockFailures = 1;
        NET_DeadlineFromNow(5, &deadline);
        Check(deadline.tv_sec == 0 && deadline.tv_nsec == 0,
              "deadline after a clock read failure is zeroed, not left uninitialised");
    }

    printf("\\n%%d checks, %%d failures\\n", g_checks, g_failures);
    return g_failures == 0 ? 0 : 1;
}
"""
    )

    # Collapse the doubled percent signs first: the case tables carry real C
    # format specifiers that must survive into the generated source.
    return (
        template.replace("%%", "%")
        .replace("__REMAINING__", cases)
        .replace("__DEADLINE__", deadline_cases)
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--cxx", default=os.environ.get("CXX", "clang++"),
                        help="C++ compiler (default: clang++, or $CXX)")
    parser.add_argument("--timeout", type=int, default=120,
                        help="hard timeout for the compiled harness, in seconds")
    args = parser.parse_args()

    if not NET_SOURCE.is_file():
        print(f"FAIL: {NET_SOURCE} is missing", file=sys.stderr)
        return 2

    source = NET_SOURCE.read_text(encoding="utf-8", errors="replace")
    extracted = "".join(extract_function(source, name) for name in EXTRACTED)

    workdir = Path(tempfile.mkdtemp(prefix="kisakcod_net_deadline_"))
    try:
        harness = workdir / "deadline_harness.cpp"
        harness.write_text(build_harness(extracted), encoding="utf-8")

        binary = workdir / "deadline_harness"
        compile_cmd = [
            args.cxx, "-m32", "-std=c++20", "-O1", "-g",
            "-Wall", "-Wextra", "-Wno-unused-parameter",
            str(harness), "-o", str(binary),
        ]

        compiled = subprocess.run(compile_cmd, capture_output=True, text=True)
        if compiled.returncode != 0:
            print("FAIL: harness did not compile", file=sys.stderr)
            print(" ".join(compile_cmd), file=sys.stderr)
            print(compiled.stdout, file=sys.stderr)
            print(compiled.stderr, file=sys.stderr)
            return 2
        if compiled.stderr.strip():
            print(compiled.stderr.strip(), file=sys.stderr)

        try:
            run = subprocess.run([str(binary)], capture_output=True, text=True,
                                 timeout=args.timeout)
        except subprocess.TimeoutExpired:
            print(f"FAIL: harness did not finish within {args.timeout}s", file=sys.stderr)
            return 2

        sys.stdout.write(run.stdout)
        if run.stderr.strip():
            sys.stderr.write(run.stderr)
        return run.returncode
    finally:
        shutil.rmtree(workdir, ignore_errors=True)


if __name__ == "__main__":
    raise SystemExit(main())
