"""Opt-in live check of server-side test clients on an isolated loopback server.

``addtestclient()`` (GSC) calls ``SV_AddTestClient``, which fills a ``client_t``
slot with an internal ``NA_BOT`` client. That client never authenticates and
never sends packets; ``SV_BotUserMove`` drives it from the server frame.

Isolation: only symlinks to the installed ``main``/``zone`` and
``localization.txt`` are staged. ``fs_homepath`` and the mod directory are fresh
temporary directories, so nothing is written inside the game installation. The
server binds ``127.0.0.1`` on an OS-chosen ephemeral port and is never told to
advertise, so it cannot collide with a server on 28960 or a relay on 28961.

Authentication stays at its defaults, and the fixture proves it from inside the
game with ``getdvar`` markers rather than trusting the command line. The bots
need no identity: ``NA_BOT`` is a local pseudo-address, so the handshake paths
that require Steam tickets are never entered.

Fixture gametype: ``SV_SetGametype`` validates ``g_gametype`` against the
registered list and rewrites anything unknown to ``dm``, so the fixture overrides
``maps/mp/gametypes/dm.gsc`` (a *valid* stock name) from ``fs_game``, which
``Scr_ReadFile`` reads before the fastfile even with ``useFastFile 1``. Its
``main`` starts the test thread *first*, then calls the stock
``maps\\mp\\gametypes\\war::main`` so ordinary game-type start-up still runs.
This is a test fixture only: it is not real stock DM, and the war start-up it
calls is not what a DM round would run.

Markers use ``logprint`` (builtin flag 0), which reaches ``games_mp.log`` even
with ``developer 0``; ``println`` is developer-gated (flag 1) and was silently
discarded, which is why earlier runs showed live bots but no markers.

The fixture marks internal clients with the stock scripts' pers["isBot"] field
and submits normal team/class menu responses. It never sets sessionstate or
calls spawn directly. Repeated hold samples require the same healthy, playing
clients with the selected team, class and a weapon, followed by clean shutdown.

With --cycles, the same admitted entity/name pairs are checked after repeated
map_restart, map mp_shipment and map_rotate transitions. No replacements are
admitted. A fixture connect callback restores the stock isBot script flag only
for those exact pairs, before the normal callback checks retail class stats.

With --refill-cycles, sv_maxclients equals the bot count so every refill must
reuse freed slots. The fixture performs real GSC kick/SV_DropClient, waits the
default zombie grace period plus two seconds, verifies disappearance, then
admits a new cohort. Both teams are used through normal menus to respect team
capacity; sv_botsPressAttackBtn=0 keeps combat out of these lifecycle checks.
Map cycles, if requested, retain the final refill cohort.

NOT implemented or claimed: combat kills, client-originated disconnect packets,
client-side/snapshot decoding, retail/Steam compatibility, and AI.

Usage:
    python3 scripts/tests/test_linux_bots.py "/path/to/Call of Duty 4" \
        --binary build-bots/bin/KisakCOD-dedi --bots 3 --timeout 45
"""

